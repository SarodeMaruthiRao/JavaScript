/* Operator
   - Operator is a symbol is used to perform operations between two operands
     Example:- a+b
              (a,b) --> operands
              ( + )--> operator
*/

/* Arthimatic Operators
   - It is used to perform basic Mathematical operations.
   - List of Arthimatic Operators
     1.Addition (+)
     2.Substraction (-)
     3.Multiplication (*)
     4.Division (/)
     5.Modulo Division (%)
     6.Expotential (**)
*/
let a = 2;
let b = 5;

console.log("a = ",a ,"& b = ",b)
console.log("a + b =",a+b);
console.log("a - b =",a-b);
console.log("a * b =",a*b);
console.log("a / b =",a/b);
console.log("a % b =",a%b);
console.log("a ** b =",a**b);



/* Increment and Decrement Operators
        Increment - (++)
        Decrement - (--)
    pre --> assignment next operation
    post --> operation next assignment
*/
let num = 30
console.log("------increment and Decrement Operators------")
console.log("post Increment:-",num++) // post Increment
console.log("post Decrement:-",num--); // post Decrement
console.log("pre Increment:-",++num) // pre Increment
console.log("pre Decrement:-",--num); // pre Decrement





































