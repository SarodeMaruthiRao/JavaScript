
/* Assignment Operators 
   - It is Used to assign values to variable.
   - It also uses the combination of Arthimatic Operators.
   - List of Assignment with Arthimatic Operators
     1.a+=b --> a=a+b
     2.a-=b --> a=a-b
     3.a*=b --> a=a*b
     4.a/=b --> a=a/b
     5.a%=b --> a=a%b
     6.a**=b -> a=a**b

*/
let a = 20;
let b = 30;
console.log("------Assignment Operators------")
console.log("a=a+b:-",a+=b) // a=a+b
console.log("a=a-b:-",a-=b) // a=a-b
console.log("a=a*b",a*=b) // a=a*b
console.log("a=a/b",a/=b) // a=a/b
console.log("a=a%b",a%=b) // a=a%b
console.log("a=a**b:-",a**=b) // a=a**b