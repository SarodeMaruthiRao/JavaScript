
/* Ternary Operator
     - It is also called as conditional Operator
     - syntax:-
       exp?:res1:res2;
*/

let a14 = 100;
let a21 = 200;
let res = (a14>a21)?true:false;
console.log("------Ternary Operator------")
console.log(res);

